def all_symbols() -> list[tuple[str, str, str, str]]:
    """扁平化所有符号，便于统计与导出。"""
    return [item for _, items in CATEGORIES for item in items]


def category_names() -> list[str]:
    return [name for name, _ in CATEGORIES]


def count() -> int:
    return sum(len(items) for _, items in CATEGORIES)


# ---------------------------------------------------------------- 符号页布局
@dataclass
class Cell:
    """一个可点击格子：sid 形如 SYM:0 / CAT:1 / NAV:-1"""
    sid: str
    char: str
    name: str
    alt: str
    uni: str
    x: float
    y: float
    w: float
    h: float
    kind: str                 # 'sym' / 'cat' / 'nav'
    active: bool = False


def build_page(cfg: dict, category: int = 0) -> tuple[list[Cell], int, int, int]:
    """
    构造符号页格子几何，返回 (cells, canvas_w, canvas_h, header_h)。

    v4.09：画布尺寸强制等于虚拟键盘画布（调用 layout.build），且网格行数按
    「符号最多的分类」固定 —— 切换分类时画布与格子尺寸都不再变化，点击位置
    稳定，不再出现「点的时候变来变去」。
    coordinates 为图像局部像素坐标，与渲染共用同一批 Cell，命中天然对齐。
    """
    import layout
    category = max(0, min(len(CATEGORIES) - 1, int(category)))
    sw, sh = cfg.get("screen_w", 1920), cfg.get("screen_h", 1080)
    scale = max(0.5, min(2.0, float(cfg.get("kb_scale", 1.0) or 1.0)))
    # 与键盘完全相同的画布尺寸
    _, cw, ch, unit, header = layout.build(
        cfg.get("layout", "compact"), bool(cfg.get("narrow", False)), sw, scale)

    pad = max(14, int(unit * 0.24))
    cat_h = max(26, int(unit * 0.54))
    cat_gap = max(5, int(unit * 0.10))
    footer = max(24, int(unit * 0.42))
    gap = max(6, int(unit * 0.16))

    cols = 8
    # 固定行数：按符号最多的分类决定，所有分类共用同一套网格几何
    max_items = max(len(items) for _, items in CATEGORIES)
    rows = max(1, math.ceil(max_items / cols))
    grid_top = header + cat_h + 12
    grid_h = max(rows * 46, ch - grid_top - footer - pad)
    cell_w = (cw - pad * 2 - (cols - 1) * gap) / cols
    cell_h = (grid_h - (rows - 1) * gap) / rows
    grid_w = cols * cell_w + (cols - 1) * gap

    cells: list[Cell] = []
    # 分类标签行（顶部），均匀铺满画布宽度
    ncat = len(CATEGORIES)
    cat_w = (cw - pad * 2 - cat_gap * (ncat - 1)) // ncat
    cy = header + 3
    for i, (name, _) in enumerate(CATEGORIES):
        cells.append(Cell("CAT:%d" % i, "", name, "", "",
                          pad + i * (cat_w + cat_gap), cy, cat_w, cat_h,
                          "cat", active=(i == category)))

    # 符号网格：固定 rows 行，符号按序自上而下填入，其余格子留空
    gx0 = (cw - grid_w) / 2
    gy0 = grid_top
    items = CATEGORIES[category][1]
    for i, (ch_, name, alt, uni) in enumerate(items):
        r, c = divmod(i, cols)
        cells.append(Cell("SYM:%d" % i, ch_, name, alt, uni,
                          gx0 + c * (cell_w + gap), gy0 + r * (cell_h + gap),
                          cell_w, cell_h, "sym"))
    return cells, cw, ch, header


def symbol_at(category: int, index: int):
    """取 (char, name, alt, uni)，越界返回 None。"""
    try:
        return CATEGORIES[category][1][index]
    except (IndexError, ValueError):
        return None


