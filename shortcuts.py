def detect_app(exe_name: str) -> str:
    """根据前台进程名返回情境 key，未命中返回 'generic'"""
    if not exe_name:
        return "generic"
    name = exe_name.lower()
    for key, prof in APP_PROFILES.items():
        for e in prof["exe"]:
            if e in name:
                return key
    return "generic"


def resolve(combo: str, app_key: str, custom: dict | None = None) -> dict[str, str]:
    """组合键 + 情境 -> {键位id: 指令文本}；越靠后的优先级越高"""
    combo = db_combo(combo)
    result: dict[str, str] = {}
    result.update(GENERIC.get(combo, {}))
    if app_key in APP_PROFILES:
        result.update(APP_PROFILES[app_key]["tips"].get(combo, {}))
    if custom:
        # 自定义配置里写「Ctrl+Win」或「Win+Ctrl」都认
        for name, table in custom.items():
            if db_combo(name) == combo and isinstance(table, dict):
                result.update(table)
    # 过滤掉空值（用户可用 "" 隐藏某条）
    return {k: v for k, v in result.items() if v}


def app_display_name(app_key: str) -> str:
    if app_key == "generic":
        return "通用"
    return APP_PROFILES.get(app_key, {}).get("name", "通用")


