from __future__ import annotations

# 组合名的规范顺序，用于把当前按住的修饰键集合转换成数据库主键
MOD_ORDER = ["Ctrl", "Shift", "Alt", "Win"]
MOD_DISPLAY = {"Ctrl": "Ctrl", "Shift": "Shift", "Alt": "Alt", "Win": "Win"}


def combo_name(mods) -> str:
    """mods: 可迭代的修饰键名 -> 'Ctrl+Shift' 这类规范组合名（用于界面显示）"""
    s = set(mods)
    return "+".join(m for m in MOD_ORDER if m in s)


# 显示名 -> 数据库键名（保留「Win+Shift」「Alt+Shift」这类更符合习惯的写法）
_COMBO_ALIAS = {
    "Ctrl+Win": "Win+Ctrl",
    "Shift+Alt": "Alt+Shift",
    "Shift+Win": "Win+Shift",
    "Alt+Win": "Win+Alt",
}


def db_combo(combo: str) -> str:
    return _COMBO_ALIAS.get(combo, combo)


